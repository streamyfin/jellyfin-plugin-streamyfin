using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace Jellyfin.Plugin.Streamyfin.Db;

/// <summary>
/// The plugin's persistence, over EF Core.
/// </summary>
/// <remarks>
/// A context is created per operation rather than held. Contexts are cheap, and
/// a short lived one keeps the change tracker from growing and removes the need
/// for the reader writer lock the hand written store carried.
/// </remarks>
public class PluginDatabase
{
    /// <summary>
    /// The database written by the hand written SQLite store this replaces.
    /// It is read once and then left alone, so downgrading still finds its data.
    /// </summary>
    internal const string LegacyFileName = "streamyfin_plugin.db";

    private const string FileName = "streamyfin.db";

    private readonly ILogger<PluginDatabase>? _logger;

    /// <summary>
    /// Initializes a new instance of the <see cref="PluginDatabase"/> class, applying
    /// migrations and running any pending one time import.
    /// </summary>
    /// <param name="path">Directory the database lives in.</param>
    /// <param name="logger">Optional logger.</param>
    public PluginDatabase(string path, ILogger<PluginDatabase>? logger = null)
    {
        ArgumentNullException.ThrowIfNull(path);

        _logger = logger;
        Directory.CreateDirectory(path);
        DbFilePath = Path.Combine(path, FileName);
        LegacyDbFilePath = Path.Combine(path, LegacyFileName);

        using var context = CreateContext();
        context.Database.Migrate();

        ImportLegacyDeviceTokens(context);
    }

    /// <summary>
    /// Gets the full path of the database file.
    /// </summary>
    public string DbFilePath { get; }

    /// <summary>
    /// Gets the full path of the database this one replaced.
    /// </summary>
    internal string LegacyDbFilePath { get; }

    /// <summary>
    /// Creates a context against this database.
    /// </summary>
    /// <returns>A new context the caller owns.</returns>
    public StreamyfinDbContext CreateContext() => new(DbFilePath);

    /// <summary>
    /// Gets the push tokens for every device a user is currently signed in on.
    /// </summary>
    /// <param name="userId">Jellyfin user id.</param>
    /// <returns>The user's device tokens.</returns>
    public List<DeviceToken> GetUserDeviceTokens(Guid userId)
    {
        using var context = CreateContext();
        return context.DeviceTokens.AsNoTracking()
            .Where(t => t.UserId == userId)
            .ToList();
    }

    /// <summary>
    /// Gets every known device token.
    /// </summary>
    /// <returns>All device tokens.</returns>
    public List<DeviceToken> GetAllDeviceTokens()
    {
        using var context = CreateContext();
        return context.DeviceTokens.AsNoTracking().ToList();
    }

    /// <summary>
    /// Gets the token registered for one device.
    /// </summary>
    /// <param name="deviceId">Device id generated by the app.</param>
    /// <returns>The token, or <c>null</c> when the device is unknown.</returns>
    public DeviceToken? GetDeviceTokenForDeviceId(Guid deviceId)
    {
        using var context = CreateContext();
        return context.DeviceTokens.AsNoTracking()
            .FirstOrDefault(t => t.DeviceId == deviceId);
    }

    /// <summary>
    /// Registers a token for a device, replacing whatever that device had before.
    /// </summary>
    /// <param name="token">The token to store. Its timestamp is set here.</param>
    /// <returns>The stored token, with its timestamp.</returns>
    public DeviceToken AddDeviceToken(DeviceToken token)
    {
        ArgumentNullException.ThrowIfNull(token);

        using var context = CreateContext();

        var existing = context.DeviceTokens.FirstOrDefault(t => t.DeviceId == token.DeviceId);
        if (existing is not null)
        {
            context.DeviceTokens.Remove(existing);
            context.SaveChanges();
        }

        token.Timestamp = DateTime.UtcNow.ToFileTime();
        context.DeviceTokens.Add(token);
        context.SaveChanges();

        return token;
    }

    /// <summary>
    /// Counts the registered devices.
    /// </summary>
    /// <returns>How many device tokens are stored.</returns>
    public long TotalDevicesCount()
    {
        using var context = CreateContext();
        return context.DeviceTokens.LongCount();
    }

    /// <summary>
    /// Forgets a device.
    /// </summary>
    /// <param name="deviceId">Device id generated by the app.</param>
    public void RemoveDeviceToken(Guid deviceId)
    {
        using var context = CreateContext();

        var existing = context.DeviceTokens.FirstOrDefault(t => t.DeviceId == deviceId);
        if (existing is null)
        {
            return;
        }

        context.DeviceTokens.Remove(existing);
        context.SaveChanges();
    }

    /// <summary>
    /// Removes every device token.
    /// </summary>
    public void Purge()
    {
        using var context = CreateContext();
        context.DeviceTokens.RemoveRange(context.DeviceTokens);
        context.SaveChanges();
    }

    /// <summary>
    /// Carries device tokens over from the hand written store, once.
    /// </summary>
    /// <remarks>
    /// Failure is not fatal. A server that cannot read the old file still starts,
    /// keeps working with an empty table, and tries again next time, which is the
    /// only acceptable behaviour for something that runs during plugin activation.
    /// </remarks>
    /// <param name="context">An open context on the new database.</param>
    private void ImportLegacyDeviceTokens(StreamyfinDbContext context)
    {
        if (context.ImportMarkers.Any(m => m.Name == ImportMarker.LegacyDeviceTokens))
        {
            return;
        }

        if (!File.Exists(LegacyDbFilePath))
        {
            MarkImported(context, 0);
            return;
        }

        List<DeviceToken> legacy;
        try
        {
            legacy = LegacyDeviceTokenReader.Read(LegacyDbFilePath);
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(
                ex,
                "Could not read the previous database at {Path}. Device tokens were not imported and the import will be retried on the next start",
                LegacyDbFilePath);
            return;
        }

        try
        {
            var known = context.DeviceTokens.Select(t => t.DeviceId).ToHashSet();
            var fresh = legacy.Where(t => !known.Contains(t.DeviceId)).ToList();

            using var transaction = context.Database.BeginTransaction();
            context.DeviceTokens.AddRange(fresh);
            context.ImportMarkers.Add(new ImportMarker
            {
                Name = ImportMarker.LegacyDeviceTokens,
                ImportedAt = DateTimeOffset.UtcNow,
                RowsImported = fresh.Count
            });
            context.SaveChanges();
            transaction.Commit();

            _logger?.LogInformation(
                "Imported {Count} device token(s) from {Path}. The old file is left in place and is not read again",
                fresh.Count,
                LegacyDbFilePath);
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(
                ex,
                "Could not import device tokens from {Path}. The import will be retried on the next start",
                LegacyDbFilePath);
        }
    }

    private static void MarkImported(StreamyfinDbContext context, int rows)
    {
        context.ImportMarkers.Add(new ImportMarker
        {
            Name = ImportMarker.LegacyDeviceTokens,
            ImportedAt = DateTimeOffset.UtcNow,
            RowsImported = rows
        });
        context.SaveChanges();
    }
}
