    /// <summary>
    /// Registers a token for a device, replacing whatever that device had before.
    /// </summary>
    /// <param name="token">The token to store. Its timestamp is set here.</param>
    /// <returns>The stored token, with its timestamp.</returns>
    public DeviceToken AddDeviceToken(DeviceToken token)
    {
        ArgumentNullException.ThrowIfNull(token);

        using var context = CreateContext();

        // A token is one installation of the app, so it has one owner: the device that
        // registered it last. Expo keeps an iOS token through a reinstall while the app
        // starts over with a new device id, and the row left behind sent the previous
        // account's notifications to whoever signed in next. One transaction, or two
        // devices registering the same token could both find nothing to remove.
        using var transaction = context.Database.BeginTransaction();

        // Stamped once the write lock is held rather than before waiting for it. A
        // registration that waited stamped itself with the moment it started, and the
        // pruning of a push sent in between then took it for the device that push went to.
        var timestamp = DateTime.UtcNow.ToFileTime();

        // A row carrying no token is nobody's installation, so it neither takes the others
        // with it nor is taken by them. The route refuses such a registration; this is for
        // the rows an older build could have stored.
        if (!string.IsNullOrWhiteSpace(token.Token))
        {
            context.DeviceTokens
                .Where(t => t.Token == token.Token && t.DeviceId != token.DeviceId)
                .ExecuteDelete();
        }

        // One statement, so two registrations of the same device cannot race each
        // other. The app posts its token twice on sign in, and a lookup followed by an
        // insert let the second one fail on the device id with a 500 while the first
        // was still saving. An existing row is updated in place, never removed and
        // re-added, so a device is never left without a token between two writes.
        context.Database.ExecuteSqlInterpolated($"""
            INSERT INTO DeviceTokens (DeviceId, Token, UserId, Language, ServerUrl, Timestamp)
            VALUES ({token.DeviceId}, {token.Token}, {token.UserId}, {token.Language}, {token.ServerUrl}, {timestamp})
            ON CONFLICT(DeviceId) DO UPDATE SET
                Token = excluded.Token,
                UserId = excluded.UserId,
                Language = excluded.Language,
                ServerUrl = excluded.ServerUrl,
                Timestamp = excluded.Timestamp
            """);

        transaction.Commit();

        token.Timestamp = timestamp;
        return token;
    }

    /// <summary>
    /// Counts the registered devices.
    /// </summary>
    /// <returns>How many device tokens are stored.</returns>
    public long TotalDevicesCount()
    {
        using var context = CreateContext();
        return context.DeviceTokens.LongCount();
    }

    /// <summary>
    /// Forgets a device, when it belongs to the account asking.
    /// </summary>
    /// <param name="deviceId">Device id generated by the app.</param>
    /// <param name="owner">
    /// The account the row must belong to, or <c>null</c> to remove it whoever holds it,
    /// which is what an administrator's API key asks for.
    /// </param>
    /// <remarks>
    /// One statement, for the same reason the registration is: a lookup followed by a
    /// delete let a second call at the same moment fail its concurrency check on the row
    /// the first had already removed.
    /// </remarks>
    public void RemoveDeviceToken(Guid deviceId, Guid? owner = null)
    {
        using var context = CreateContext();

        context.DeviceTokens
            .Where(t => t.DeviceId == deviceId && (owner == null || t.UserId == owner))
            .ExecuteDelete();
    }

    /// <summary>
    /// Forgets every device registered under a token Expo has reported as gone, unless it
    /// registered after the push Expo was answering about.
    /// </summary>
    /// <param name="dead">
    /// The dead Expo push tokens, each with the moment the push it answers was sent, in
    /// UTC.
    /// </param>
    /// <returns>How many device rows were removed.</returns>
    /// <remarks>
    /// By token rather than by device id, because that is the only thing Expo names, and
    /// every row carrying it goes, since a build before one owner per token could have
    /// left more than one.
    ///
    /// <para>
    /// The moment matters for the timeline this pair of changes is about: a push goes to a
    /// device, the app is reinstalled, and somebody signs in on it before Expo's answer is
    /// collected. Expo reports the token as gone, which was true of the installation that
    /// was sent to, and a row written since belongs to the one that replaced it.
    /// </para>
    /// </remarks>
    public int RemoveDeviceTokensNamed(IReadOnlyDictionary<string, DateTime> dead)
    {
        ArgumentNullException.ThrowIfNull(dead);

        if (dead.Count == 0)
        {
            return 0;
        }

        using var context = CreateContext();

        var removed = 0;

        foreach (var (token, sentAt) in dead)
        {
            if (string.IsNullOrWhiteSpace(token))
            {
                continue;
            }

            var sent = AsUtc(sentAt).ToFileTimeUtc();

            // One statement per token. Two sends told about the same dead tokens at once
            // each loaded the rows and then deleted them, and the second delete failed its
            // concurrency check. A delete that finds the rows gone counts nothing and
            // carries on.
            removed += context.DeviceTokens
                .Where(t => t.Token == token && t.Timestamp <= sent)
                .ExecuteDelete();
        }

        return removed;
    }

    /// <summary>
    /// The same moment, as UTC. A time read back from SQLite carries no kind, and these
    /// are all written in UTC, so a server east or west of it would otherwise compare a
    /// push against registrations made hours away from it.
    /// </summary>
    /// <param name="moment">The moment, in UTC or with no kind at all.</param>
    /// <returns>The moment, marked as UTC.</returns>
    private static DateTime AsUtc(DateTime moment) => moment.Kind switch
    {
        DateTimeKind.Utc => moment,
        DateTimeKind.Local => moment.ToUniversalTime(),
        _ => DateTime.SpecifyKind(moment, DateTimeKind.Utc)
    };

    /// <summary>
    /// Remembers the pushes Expo accepted, so their receipts can be asked for later.
    /// </summary>
    /// <param name="receipts">The ticket and token pairs.</param>
    /// <param name="now">When the send happened, in UTC.</param>
    /// <remarks>
    /// A ticket id already stored is skipped rather than replaced. Expo does not reissue
    /// them, so a collision would mean something is wrong upstream and the first row is
    /// the one that knows which token it belonged to.
    /// </remarks>
    public void AddExpoReceipts(IEnumerable<(string TicketId, string Token)> receipts, DateTime now)
    {
        ArgumentNullException.ThrowIfNull(receipts);

        var incoming = receipts.ToList();
        if (incoming.Count == 0)
        {
            return;
        }

        using var context = CreateContext();

        var ids = incoming.Select(r => r.TicketId).ToList();
        var known = context.ExpoReceipts
            .Where(r => ids.Contains(r.TicketId))
            .Select(r => r.TicketId)
            .ToHashSet(StringComparer.Ordinal);

        var rows = incoming
            .Where(r => known.Add(r.TicketId))
            .Select(r => new ExpoReceipt { TicketId = r.TicketId, Token = r.Token, CreatedAt = now })
            .ToList();

        if (rows.Count == 0)
        {
            return;
        }

        context.ExpoReceipts.AddRange(rows);
        context.SaveChanges();
    }

    /// <summary>
    /// The pushes old enough for Expo to have produced a receipt.
    /// </summary>
    /// <param name="sentBefore">Only pushes older than this, in UTC.</param>
    /// <param name="limit">At most this many, since Expo takes 1000 ids per request.</param>
    /// <param name="excluding">Ticket ids to skip, typically the ones already asked about.</param>
    /// <returns>The oldest ones first.</returns>
    /// <remarks>
    /// The exclusion belongs in the query rather than in the caller, and that is not a
    /// preference. A push Expo has not resolved keeps its row, so filtering after the
    /// limit hands back the same oldest batch every time: a run whose first batch went
    /// entirely unanswered would take that batch, filter it away, find nothing new and
    /// stop, and everything behind it would wait for those rows to resolve or expire.
    /// Excluding before the limit is what lets a backlog actually be walked.
    /// </remarks>
    public List<ExpoReceipt> GetExpoReceiptsSentBefore(
        DateTime sentBefore,
        int limit,
        IReadOnlyCollection<string>? excluding = null)
    {
        using var context = CreateContext();

        var query = context.ExpoReceipts.AsNoTracking()
            .Where(r => r.CreatedAt <= sentBefore);

        if (excluding is { Count: > 0 })
        {
            query = query.Where(r => !excluding.Contains(r.TicketId));
        }

        return query
            .OrderBy(r => r.CreatedAt)
            .ThenBy(r => r.TicketId)
            .Take(limit)
            .ToList();
    }

    /// <summary>
    /// Forgets pushes, whether they were answered or have simply expired.
    /// </summary>
    /// <param name="ticketIds">The ticket ids to drop.</param>
    public void RemoveExpoReceipts(IEnumerable<string> ticketIds)
    {
        ArgumentNullException.ThrowIfNull(ticketIds);

        var ids = ticketIds.Distinct(StringComparer.Ordinal).ToList();
        if (ids.Count == 0)
        {
            return;
        }

        using var context = CreateContext();

        var rows = context.ExpoReceipts.Where(r => ids.Contains(r.TicketId)).ToList();
        if (rows.Count == 0)
        {
            return;
        }

        context.ExpoReceipts.RemoveRange(rows);
        context.SaveChanges();
    }

    /// <summary>
    /// Forgets pushes Expo would no longer answer for.
    /// </summary>
    /// <param name="sentBefore">Only pushes older than this, in UTC.</param>
    /// <returns>How many rows were dropped.</returns>
    /// <remarks>
    /// Expo keeps a receipt for 24 hours. Past that the answer is never coming, and a row
    /// that is never removed is the same accumulation in a different table.
    /// </remarks>
    public int RemoveExpoReceiptsSentBefore(DateTime sentBefore)
    {
        using var context = CreateContext();

        var rows = context.ExpoReceipts.Where(r => r.CreatedAt <= sentBefore).ToList();
        if (rows.Count == 0)
        {
            return 0;
        }

        context.ExpoReceipts.RemoveRange(rows);
        context.SaveChanges();

        return rows.Count;
    }

