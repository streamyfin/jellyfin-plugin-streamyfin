    /// <summary>
    /// Carries device tokens over from the hand written store, once.
    /// </summary>
    /// <remarks>
    /// Failure is not fatal. A server that cannot read the old file still starts,
    /// keeps working with an empty table, and tries again next time, which is the
    /// only acceptable behaviour for something that runs during plugin activation.
    /// </remarks>
    /// <param name="context">An open context on the new database.</param>
    private void ImportLegacyDeviceTokens(StreamyfinDbContext context)
    {
        if (context.ImportMarkers.Any(m => m.Name == ImportMarker.LegacyDeviceTokens))
        {
            return;
        }

        if (!File.Exists(LegacyDbFilePath))
        {
            MarkImported(context, 0);
            return;
        }

        List<DeviceToken> legacy;
        try
        {
            legacy = LegacyDeviceTokenReader.Read(LegacyDbFilePath);
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(
                ex,
                "Could not read the previous database at {Path}. Device tokens were not imported and the import will be retried on the next start",
                LegacyDbFilePath);
            return;
        }

        try
        {
            var known = context.DeviceTokens.Select(t => t.DeviceId).ToHashSet();
            var fresh = legacy.Where(t => !known.Contains(t.DeviceId)).ToList();

            using var transaction = context.Database.BeginTransaction();
            context.DeviceTokens.AddRange(fresh);
            context.ImportMarkers.Add(new ImportMarker
            {
                Name = ImportMarker.LegacyDeviceTokens,
                ImportedAt = DateTimeOffset.UtcNow,
                RowsImported = fresh.Count
            });
            context.SaveChanges();
            transaction.Commit();

            _logger?.LogInformation(
                "Imported {Count} device token(s) from {Path}. The old file is left in place and is not read again",
                fresh.Count,
                LegacyDbFilePath);
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(
                ex,
                "Could not import device tokens from {Path}. The import will be retried on the next start",
                LegacyDbFilePath);
        }
    }

    /// <summary>
    /// Leaves each push token on one row, the one registered last.
    /// </summary>
    /// <remarks>
    /// Registration keeps it that way from this version on. This is for the rows stored
    /// before, by an earlier build or by the import, where a reinstalled iOS device could
    /// be on two rows under two accounts. One statement, and it runs on every start since
    /// it has nothing to do once the table is clean. Failure is not fatal, for the same
    /// reason the import's is not.
    /// </remarks>
    /// <param name="context">An open context on the new database.</param>
    private void KeepOneRowPerToken(StreamyfinDbContext context)
    {
        try
        {
            // The device id breaks a tie between two rows stamped at the same moment, so
            // exactly one of them stays.
            var removed = context.Database.ExecuteSqlRaw("""
                DELETE FROM DeviceTokens
                WHERE trim(Token) <> ''
                  AND EXISTS (
                    SELECT 1 FROM DeviceTokens AS newer
                    WHERE newer.Token = DeviceTokens.Token
                      AND (newer.Timestamp > DeviceTokens.Timestamp
                           OR (newer.Timestamp = DeviceTokens.Timestamp AND newer.DeviceId > DeviceTokens.DeviceId)))
                """);

            if (removed > 0)
            {
                _logger?.LogInformation(
                    "Removed {Count} device registration(s) whose push token a newer registration carries",
                    removed);
            }
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(
                ex,
                "Could not remove the older registrations of a push token. This is tried again on the next start");
        }
    }

    private static void Upsert(StreamyfinDbContext context, string id, string configJson)
    {
        var existing = context.GlobalConfigurations.FirstOrDefault(c => c.Id == id);

        if (existing is null)
        {
            context.GlobalConfigurations.Add(new GlobalConfiguration
            {
                Id = id,
                ConfigJson = configJson
            });
        }
        else
        {
            existing.ConfigJson = configJson;
        }
    }

    private static void MarkImported(StreamyfinDbContext context, int rows)
    {
        context.ImportMarkers.Add(new ImportMarker
        {
            Name = ImportMarker.LegacyDeviceTokens,
            ImportedAt = DateTimeOffset.UtcNow,
            RowsImported = rows
        });
        context.SaveChanges();
    }
